      WHEN IFNULL(
        CASE
          WHEN LEFT(f._BIC_ZWWPC_PA1,2) = 'FS' THEN f.FS_COMP_WK
          WHEN LEFT(f._BIC_ZWWPC_PA1,2) = 'RX' THEN f.RX_COMP_WK
          ELSE f.FS_COMP_WK
        END, '0'
      ) IS NULL THEN '0'
      ELSE
        CASE
          WHEN LEFT(f._BIC_ZWWPC_PA1,2) = 'FS' THEN f.FS_COMP_WK
          WHEN LEFT(f._BIC_ZWWPC_PA1,2) = 'RX' THEN f.RX_COMP_WK
