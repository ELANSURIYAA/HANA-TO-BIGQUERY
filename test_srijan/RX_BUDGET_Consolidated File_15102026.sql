    f._B631_S_CO_AREA,
    f._BIC_ZIO_CMPCD,
    f._B631_S_PROFTCTR,
    CASE
      WHEN LEFT(f._BIC_ZWWPC_PA1,2) = 'FS' THEN 'FS'
      WHEN LEFT(f._BIC_ZWWPC_PA1,2) = 'RX' THEN 'RX'
      ELSE ''
    END AS CAL_FS_RX_FLAG,
